#!/usr/bin/env python3
"""The back-end modules' contracts (scripts/comb/gen_top_order.py schedules their phases with the other tops').

Every back-end module declares its comb phases above its class (docs/MODULE_CONTRACT.md):
    //   CONTRACT <phase>  in: <fields | ->  out: <fields | ->
    //   CONTRACT owns: <fields>
(comb_graph.py checks these declarations against the code). The order of BackTop::comb() follows from them:
  * a module's phases run in the order its header lists them (they also share the module's private state);
  * a phase that writes a field runs before every phase of another module that reads it;
  * the phases that use the trace bridge (tbhook::, side effects outside the Wires) keep the order of TB_ORDER.
Other direct accesses between modules read registers (q), which do not change during comb: no order needed.
Ties are broken by MODULE_PRIORITY, not by the current code, so the generated order depends on the declarations only.
A phase that reads a field another top drives after BackTop::comb() (the fields of BackTop's `EXPORT comb_late` in-ports,
through the port table in include/SimCpu.h), and every phase after it in the graph, goes to BackTop::comb_late().

usage: gen_comb_order.py          print the generated order
       gen_comb_order.py --write  rewrite the generated block of BackTop::comb() (back-end/BackTop.cpp)
       gen_comb_order.py --check  exit 1 if the block differs from the declarations
"""
import os, re, sys
from contract_lib import topo

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODULES = {'pre': 'PreIduQueue', 'idu': 'Idu', 'rename': 'Ren', 'dis': 'Dispatch', 'isu': 'Isu', 'exu': 'Exu',
           'rob': 'Rob', 'csr': 'Csr', 'lsu': 'RealLsu'}
MODULE_PRIORITY = ['pre', 'rename', 'idu', 'lsu', 'csr', 'rob', 'dis', 'exu', 'isu']
# the trace-bridge users, in the order their side effects must happen (fact lookups of in-flight uops; BackTop's commit /
# flush updates the bridge); comb_graph.py checks that the scanned users are exactly these
TB_ORDER = ['lsu.comb_outputs', 'lsu.comb_writeback', 'exu.comb_exec', 'lsu.comb_translate', 'rob.comb_redirect',
            'rob.comb_update']
BEGIN = '  // BEGIN GENERATED by scripts/comb/gen_comb_order.py from the module contracts: do not edit\n'
BEGIN_LATE = '  // BEGIN GENERATED (late) by scripts/comb/gen_comb_order.py from the module contracts: do not edit\n'
END = '  // END GENERATED\n'


def contracts():
    hdrs = {}
    for d0, _, fs in os.walk(os.path.join(ROOT, 'back-end')):
        for f in fs:
            if f.endswith('.h'): hdrs[os.path.join(d0, f)] = open(os.path.join(d0, f), errors='ignore').read()
    out = {}
    for obj, cls in MODULES.items():
        block = None
        for t in hdrs.values():
            m = re.search(r'((?:^//[^\n]*\n)+)class ' + cls + r'\s*(?::[^{;]*)?\{', t, re.M)
            if m and 'CONTRACT' in m.group(1): block = m.group(1); break
        if block is None: sys.exit(f'{obj} ({cls}): no contract')
        phases = []
        for m in re.finditer(r'CONTRACT (\w+)\s+in:(.*?)\s+out:([^\n]*)', block):
            phases.append((m.group(1), set(m.group(2).split()) - {'-'}, set(m.group(3).split()) - {'-'}))
        out[obj] = phases
    return out


def late_fields():
    """the back-end fields of BackTop's comb_late in-ports (SimCpu.h PORT table: back.<field>)"""
    bt = open(os.path.join(ROOT, 'back-end', 'include', 'BackTop.h')).read()
    m = re.search(r'EXPORT comb_late\s+in:([^\n]*?)(?:\s+(?:pre|out|default):|$)', bt, re.M)
    if not m: return set()
    sc = open(os.path.join(ROOT, 'include', 'SimCpu.h')).read()
    ports = {p.group(1): p.group(2).split() for p in re.finditer(r'^//\s+PORT (\w+)\s*=\s*([^\n(]*)', sc, re.M)}
    out = set()
    for port in m.group(1).split():
        for path in ports.get(port, []):
            if path.startswith('back.'): out.add(path[len('back.'):])
    return out


def generate():
    c = contracts()
    nodes = [f'{o}.{p}' for o in MODULE_PRIORITY for p, _, _ in c[o]]
    ins = {f'{o}.{p}': i for o in c for p, i, _ in c[o]}
    outs = {f'{o}.{p}': w for o in c for p, _, w in c[o]}
    succ = {n: set() for n in nodes}
    for o in c:   # module order
        ps = [f'{o}.{p}' for p, _, _ in c[o]]
        for a, b in zip(ps, ps[1:]): succ[a].add(b)
    for w in nodes:   # writer before reader (other modules)
        for r in nodes:
            if w.split('.')[0] != r.split('.')[0] and outs[w] & ins[r]: succ[w].add(r)
    for a, b in zip(TB_ORDER, TB_ORDER[1:]): succ[a].add(b)
    rank = {n: i for i, n in enumerate(nodes)}   # MODULE_PRIORITY, then header order
    lf = late_fields()
    late = {n for n in nodes if ins[n] & lf}
    stack = list(late)
    while stack:
        for b in succ[stack.pop()]:
            if b not in late: late.add(b); stack.append(b)
    early = [n for n in nodes if n not in late]
    order = topo(early, {n: succ[n] & set(early) for n in early}, rank)
    order_late = topo(sorted(late, key=rank.get), {n: succ[n] & late for n in late}, rank)
    return order, order_late


def block(order, begin=BEGIN):
    lines = []
    for n in order:
        o, p = n.split('.')
        lines.append(f'  {p}();\n' if o == 'top' else f'  {o}->{p}();\n')
    return begin + ''.join(lines) + END


def main():
    print('\n'.join(generate()[0]))


if __name__ == '__main__':
    main()
