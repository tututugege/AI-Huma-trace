#!/usr/bin/env python3
"""front_comb_calc() from the front end's phase contracts.

The front end's comb phases are FrontComb's methods (front-end/front_top.cpp); its signals are FrontComb's members (the
wires of one cycle), `in` (the front end's inputs), `rd` (the registers, q), `req.<x>` (the write requests applied at
the edge, d), `out`, and `bpu_pipe.txn` (the BPU pipeline's transaction of the cycle). Declared above struct FrontComb:
    //   CONTRACT <phase>  in: <signals | ->  out: <signals | ->
    //   CONTRACT fifo <name>: <signals>  ports: <phase> <phase>   (a FIFO's state: its read port, then its write port)
comb_graph's front-domain scan must read / write exactly the declared signals. One writer per signal, except a FIFO's
state, written by its ports in the listed order. The order: the ports of a FIFO in their order, a writer before every
reader (a FIFO port does not wait for a later port of the same FIFO); ties by the header order.

usage: gen_front_order.py          print the generated order
       gen_front_order.py --emit   print CONTRACT lines from the scanned code
       gen_front_order.py --write  rewrite the generated block of front_comb_calc()
       gen_front_order.py --check  exit 1 if the declarations and the code or the block differ
"""
import os, re, sys, io, heapq, contextlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, 'front-end', 'front_top.cpp')
IGNORE = ('front_ctx', 'g_regs', 'fl', 'seen')           # the context; state used only at the edge
BPU = {'comb_cycle': ('w', 'bpu_pipe.txn'), 'txn': ('r', 'bpu_pipe.txn')}   # bpu_pipe.decide / depth read its q
BEGIN = '  // BEGIN GENERATED by scripts/comb/gen_front_order.py from the contracts above struct FrontComb: do not edit\n'
END = '  // END GENERATED\n'


def norm(keys, write):
    out = set()
    for k in keys:
        p = k.replace('[]', '').split('.')
        h = p[0]
        if h in IGNORE: continue
        if h == 'bpu_pipe':   # a method call: scanned as a read; its effect from BPU
            m = BPU.get(p[1] if len(p) > 1 else '')
            if m and (m[0] == 'w') == write: out.add(m[1])
            continue
        if h in ('in', 'rd'):
            if not write: out.add(h)   # (const: a "write" is a pointer passed on)
            continue
        out.add('.'.join(p[:2]) if h == 'req' else h)
    return {k for k in out if not any(o.startswith(k + '.') for o in out)}


def scanned():
    sys.path.insert(0, HERE)
    argv = sys.argv; sys.argv = [os.path.join(HERE, 'comb_graph.py')]
    g = {'__file__': os.path.join(HERE, 'comb_graph.py'), '__name__': 'comb_graph_for_front'}
    with contextlib.redirect_stdout(io.StringIO()):
        exec(open(os.path.join(HERE, 'comb_graph.py')).read(), g)
    sys.argv = argv
    import comb_domains
    return [(n, r, w) for n, r, w in comb_domains.FRONT_ROWS]


def declarations():
    t = open(SRC).read()
    m = re.search(r'((?:^//[^\n]*\n)+)struct FrontComb\b', t, re.M)
    if not m: sys.exit('front_top.cpp: no comment block above struct FrontComb')
    phases, fifos = [], []
    for c in re.finditer(r'^//\s+CONTRACT fifo (\w+):\s*(.*?)\s+ports:\s*([^\n]*)', m.group(1), re.M):
        fifos.append((c.group(1), set(c.group(2).split()), c.group(3).split()))
    for c in re.finditer(r'^//\s+CONTRACT (?!fifo )(\w+)\s+in:(.*?)\s+out:([^\n]*)', m.group(1), re.M):
        phases.append((c.group(1), set(c.group(2).split()) - {'-'}, set(c.group(3).split()) - {'-'}))
    return phases, fifos


def generate(phases, fifos):
    names = [p[0] for p in phases]
    ins = {p[0]: p[1] for p in phases}
    outs = {p[0]: p[2] for p in phases}
    for f, _, ports in fifos:
        for p in ports:
            if p not in ins: sys.exit(f'fifo {f}: unknown port {p}')
    succ = {n: set() for n in names}
    port_pos = {}
    for f, sigs, ports in fifos:
        for a, b in zip(ports, ports[1:]): succ[a].add(b)
        for s in sigs:
            for i, p in enumerate(ports): port_pos[(s, p)] = i
    for a in names:
        for b in names:
            if a == b: continue
            for s in outs[a] & ins[b]:
                if (s, a) in port_pos and (s, b) in port_pos and port_pos[(s, b)] < port_pos[(s, a)]: continue
                succ[a].add(b)
    indeg = {n: 0 for n in names}
    for a in names:
        for b in succ[a]: indeg[b] += 1
    rank = {n: i for i, n in enumerate(names)}
    ready = [(rank[n], n) for n in names if indeg[n] == 0]
    heapq.heapify(ready)
    order = []
    while ready:
        _, n = heapq.heappop(ready)
        order.append(n)
        for b in sorted(succ[n]):
            indeg[b] -= 1
            if indeg[b] == 0: heapq.heappush(ready, (rank[b], b))
    if len(order) != len(names): sys.exit('the contracts have a cycle: ' + ' '.join(n for n in names if indeg[n] > 0))
    return order


def check(phases, fifos, rows):
    errs = []
    D = {p[0]: p for p in phases}
    S = {n: (r, w) for n, r, w in rows}
    for n in S:
        if n not in D: errs.append(f'{n}: a front-end phase without a CONTRACT')
    for n in D:
        if n not in S: errs.append(f'CONTRACT {n}: not a phase of front_comb_calc()')
    for n, (r, w) in S.items():
        if n not in D: continue
        sin, sout = norm(r, False), norm(w | {k for k in r if k.startswith('bpu_pipe.')}, True)
        if sin != D[n][1]: errs.append(f'{n}: reads {sorted(sin)}, declared in {sorted(D[n][1])}')
        if sout != D[n][2]: errs.append(f'{n}: writes {sorted(sout)}, declared out {sorted(D[n][2])}')
    fifo_sig = {s: set(ports) for _, sigs, ports in fifos for s in sigs}
    writers = {}
    for n, _, dout in phases:
        for s in dout: writers.setdefault(s, set()).add(n)
    for s, ws in writers.items():
        if len(ws) > 1 and not ws <= fifo_sig.get(s, set()): errs.append(f'{s}: written by {" ".join(sorted(ws))}')
    return errs


def main():
    if '--emit' in sys.argv:
        for n, r, w in scanned():
            wo = norm(w | {k for k in r if k.startswith('bpu_pipe.')}, True)
            print(f'//   CONTRACT {n}  in: {" ".join(sorted(norm(r, False))) or "-"}  out: {" ".join(sorted(wo)) or "-"}')
        return
    phases, fifos = declarations()
    order = generate(phases, fifos)
    src = open(SRC).read()
    new = BEGIN + ''.join(f'  c.{n}();\n' for n in order) + END
    if '--write' in sys.argv or '--check' in sys.argv:
        a = src.find(BEGIN)
        if a < 0: sys.exit('front_comb_calc(): no generated block')
        b = src.index(END, a) + len(END)
        if '--check' in sys.argv:
            errs = check(phases, fifos, scanned())
            if src[a:b] != new: errs.append('front_comb_calc() differs from the contracts: run gen_front_order.py --write')
            for x in errs: print('  ' + x)
            if errs: sys.exit(1)
            print(f'front order: {len(order)} phases, {len(fifos)} FIFOs, as generated from the contracts')
            return
        open(SRC, 'w').write(src[:a] + new + src[b:])
        print(f'wrote {len(order)} phases')
        return
    print(' '.join(order))


if __name__ == '__main__':
    main()
